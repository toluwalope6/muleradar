import { useEffect, useRef, useState } from 'react';
import type { CaseDetail, DraftReport, TemplateReport } from '../data/types';
import { Markdown } from './Markdown';
import type { AsyncState } from '../lib/async';
import { formatDateTime, formatMoney } from '../lib/format';
import { ErrorState, SkeletonLines } from './StateViews';

interface Props {
  caseDetail: CaseDetail;
  state: AsyncState<DraftReport>;
  onGenerate: () => void;
  onClose: () => void;
}

export function reportProvenance(report: DraftReport): string {
  if (report.kind === 'sections') return 'Filled in from a fixed template using synthetic demo data; no AI service is used.';
  if (report.generatedBy === 'template') return 'Generated by the backend from a fixed template using this case’s data; no AI service was used.';
  return `Drafted on the backend by an AI model (${report.generatedBy}) from this case’s data. Check every statement against the transfers before relying on it.`;
}

function reportAsText(report: DraftReport, c: CaseDetail): string {
  if (report.kind === 'markdown') {
    return [`DRAFT FOR HUMAN REVIEW — ${reportProvenance(report)}`, `Case ${report.caseId} · retrieved ${formatDateTime(report.generatedAt)}`, '', report.markdown].join('\n');
  }
  return templateAsText(report, c);
}

function templateAsText(report: TemplateReport, c: CaseDetail): string {
  const flagged = c.transactions.filter((t) => report.evidenceTransactionIds.includes(t.id));
  const lines = [
    'DRAFT FOR HUMAN REVIEW — Demo, synthetic data',
    `Case ${report.caseId} · generated ${formatDateTime(report.generatedAt)} from a fixed template (no AI service)`,
    '',
  ];
  for (const s of report.sections) {
    lines.push(s.heading, ...s.paragraphs);
    if (s.heading.startsWith('4.')) {
      for (const t of flagged) {
        lines.push(`  ${t.id}  ${formatDateTime(t.timestamp)}  ${t.from} -> ${t.to}  ${formatMoney(t.amount, t.currency)}`);
      }
    }
    lines.push('');
  }
  return lines.join('\n');
}

export function ReportModal({ caseDetail, state, onGenerate, onClose }: Props) {
  const [copied, setCopied] = useState(false);

  const dialogRef = useRef<HTMLDivElement>(null);
  const closeRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    const opener = document.activeElement as HTMLElement | null;
    closeRef.current?.focus();
    document.body.classList.add('modal-open');
    return () => {
      document.body.classList.remove('modal-open');
      opener?.focus();
    };
  }, []);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') return onClose();
      if (e.key !== 'Tab' || !dialogRef.current) return;
      const focusable = dialogRef.current.querySelectorAll<HTMLElement>('button:not([disabled]), [href], [tabindex]:not([tabindex="-1"])');
      if (focusable.length === 0) return;
      const first = focusable[0];
      const last = focusable[focusable.length - 1];
      const inside = dialogRef.current.contains(document.activeElement);
      if (e.shiftKey && (document.activeElement === first || !inside)) {
        e.preventDefault();
        last.focus();
      } else if (!e.shiftKey && (document.activeElement === last || !inside)) {
        e.preventDefault();
        first.focus();
      }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [onClose]);

  const report = state.status === 'success' ? state.data : null;
  const flagged = report?.kind === 'sections'
    ? caseDetail.transactions
        .filter((t) => report.evidenceTransactionIds.includes(t.id))
        .sort((a, b) => a.timestamp.localeCompare(b.timestamp))
    : [];

  const copy = async () => {
    if (!report) return;
    try {
      await navigator.clipboard.writeText(reportAsText(report, caseDetail));
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      setCopied(false);
    }
  };

  const download = () => {
    if (!report) return;
    const markdown = report.kind === 'markdown';
    const url = URL.createObjectURL(new Blob([reportAsText(report, caseDetail)], { type: markdown ? 'text/markdown' : 'text/plain' }));
    const link = document.createElement('a');
    link.href = url;
    link.download = `draft-report-${report.caseId}.${markdown ? 'md' : 'txt'}`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div ref={dialogRef} className="modal" role="dialog" aria-modal="true" aria-label="Draft report" onClick={(e) => e.stopPropagation()}>
        <header className="modal-head">
          <div>
            <p className="eyebrow">Case {caseDetail.id}</p>
            <h2>Draft suspicious activity report</h2>
          </div>
          <div className="modal-actions">
            {report && (
              <>
                <button type="button" className="btn btn-quiet" onClick={copy}>
                  {copied ? 'Copied' : 'Copy'}
                </button>
                <button type="button" className="btn btn-quiet" onClick={download}>
                  Download .{report.kind === 'markdown' ? 'md' : 'txt'}
                </button>
                <button type="button" className="btn btn-quiet" onClick={onGenerate}>
                  Regenerate
                </button>
              </>
            )}
            <button ref={closeRef} type="button" className="btn btn-secondary" onClick={onClose}>
              Close
            </button>
          </div>
        </header>
        <div className="draft-banner" role="note">
          <strong>Draft for human review</strong>
          <span>Not a filed report. {report ? reportProvenance(report) : 'Indicators are reasons to review, not proof of wrongdoing.'}</span>
        </div>
        <div className="modal-body">
          {(state.status === 'loading' || state.status === 'idle') && (
            <div className="report-loading">
              <p className="muted">Building the draft from this case’s data…</p>
              <SkeletonLines rows={10} />
            </div>
          )}
          {state.status === 'error' && <ErrorState title="Couldn’t generate the draft" detail={state.error} onRetry={onGenerate} />}
          {report?.kind === 'markdown' && (
            <article className="report-doc report-md">
              <p className="small muted">Retrieved from the backend {formatDateTime(report.generatedAt)}</p>
              <Markdown source={report.markdown} />
            </article>
          )}
          {report?.kind === 'sections' && (
            <article className="report-doc">
              <p className="small muted">Generated {formatDateTime(report.generatedAt)}</p>
              {report.sections.map((s) => (
                <section key={s.heading}>
                  <h3>{s.heading}</h3>
                  {s.paragraphs.map((p, i) => (
                    <p key={i} className={p.startsWith('•') ? 'bullet' : ''}>
                      {p}
                    </p>
                  ))}
                  {s.heading.startsWith('4.') && (
                    <table className="report-table">
                      <thead>
                        <tr>
                          <th>Transfer</th>
                          <th>Time (UTC)</th>
                          <th>From → To</th>
                          <th className="num">Amount</th>
                        </tr>
                      </thead>
                      <tbody>
                        {flagged.map((t) => (
                          <tr key={t.id}>
                            <td className="mono">{t.id}</td>
                            <td className="mono">{formatDateTime(t.timestamp).replace(' UTC', '')}</td>
                            <td className="mono">
                              {t.from} → {t.to}
                            </td>
                            <td className="mono num">{formatMoney(t.amount, t.currency)}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  )}
                </section>
              ))}
            </article>
          )}
        </div>
      </div>
    </div>
  );
}
